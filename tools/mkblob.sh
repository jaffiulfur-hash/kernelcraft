#!/bin/sh
# Generate an assembly file that embeds user program ELF files into the
# kernel image and exports a table describing them.
#   usage: mkblob.sh <out.asm> <elf>...
out="$1"
shift

{
    echo "; generated by tools/mkblob.sh - do not edit"
    echo "section .rodata"
    echo "global user_programs"
    echo "global user_program_count"
    for elf in "$@"; do
        name=$(basename "$elf" .elf)
        echo "align 16"
        echo "prog_${name}_start:"
        echo "    incbin \"${elf}\""
        echo "prog_${name}_end:"
        echo "prog_${name}_name: db \"${name}\", 0"
    done
    echo "align 8"
    echo "user_programs:"
    for elf in "$@"; do
        name=$(basename "$elf" .elf)
        echo "    dq prog_${name}_name, prog_${name}_start, prog_${name}_end"
    done
    echo "user_program_count: dq $#"
} > "$out"
